#!/usr/bin/env bash
#
# check-file-size.sh — the file-size gate of PhairPlayRust.
#
# WHAT: it measures the length of every hand-written source file of the
# repository and compares it with the two limits of
# `config/performance-budgets.toml` (`code_limits.target_max_lines_per_file`
# and `code_limits.hard_max_lines_per_file`).
#
# WHY: a file that grows without a limit is a file that nobody can review
# any more. The soft limit is the target that a normal change respects; the
# hard limit is the line above which a file is a **finding** and not a
# question of taste. A finding that is never reported is not a finding.
#
# WHAT IS MEASURED: the **implementation** of the file — the lines before
# its test module. The test module is a unit of its own: the project
# keeps the tests of a module in a file of their own wherever it can, and
# a test that makes the implementation of the file unreadable does not
# make the implementation bad. The number of the test lines is reported
# next to the number of the implementation, so that nothing is hidden.
#
# THE TWO LIMITS HAVE TWO DIFFERENT WEIGHTS — and the difference is written
# down here, because a gate that is not understood is a gate that is
# switched off:
#
#   * the **soft** limit is a warning. The file is named, the count is
#     printed, the gate stays green. It is the "target" of the name.
#   * the **hard** limit is an **error**. The gate goes red. A file above
#     it has to be split before the change is handed over.
#
# The limits are read out of the budget file and are **not** repeated here:
# a number that exists in two places is a number that drifts.
#
# The files that are measured are the hand-written sources: Rust, shell,
# JavaScript, CSS, HTML, Kotlin, Swift and Python. The build artefacts, the
# archives and the vendored trees are not hand-written sources of this
# project and are not measured.
#
# A file that is **generated** is not measured either. The foreign bindings
# of the bridge, for instance, are written by `scripts/generate-bindings.sh`
# and are thousands of lines long — a limit on them would be a limit on the
# output of a tool, not on the work of a person. A file counts as generated
# when its first lines say so.
#
# Usage:
#   bash scripts/check-file-size.sh [--quiet] [--soft-only]
#
#   --soft-only   report the soft limit only; the hard limit does not fail
#                 the gate. Used to see the distance to the limit without
#                 changing the verdict of the gate.
#
# Exit code 0 = green, 1 = at least one file is above the hard limit.

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

BUDGETS="config/performance-budgets.toml"

QUIET=0
SOFT_ONLY=0
for argument in "$@"; do
  case "$argument" in
    --quiet) QUIET=1 ;;
    --soft-only) SOFT_ONLY=1 ;;
    *)
      printf 'ERROR: the argument "%s" is not known to this script.\n' "$argument" >&2
      printf 'Usage: bash scripts/check-file-size.sh [--quiet] [--soft-only]\n' >&2
      exit 2
      ;;
  esac
done

say() {
  if [ "$QUIET" -eq 0 ]; then
    printf '%s\n' "$*"
  fi
}

# Reads a numeric value out of the TOML file: key "name" -> the value of
# "name = <value>" in the section that is currently open.
toml_value() {
  local file="$1"
  local section="$2"
  local key="$3"
  awk -v section="$section" -v key="$key" '
    /^[[:space:]]*\[/ {
      current = $0
      gsub(/[[:space:]\[\]]/, "", current)
      next
    }
    current == section {
      line = $0
      sub(/#.*$/, "", line)
      n = index(line, "=")
      if (n == 0) next
      name = substr(line, 1, n - 1)
      value = substr(line, n + 1)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", name)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", value)
      if (name == key) { print value; exit }
    }
  ' "$file"
}

if [ ! -f "$BUDGETS" ]; then
  printf 'ERROR: %s is missing — the file-size limits are not configured.\n' "$BUDGETS" >&2
  exit 2
fi

SOFT_LIMIT="$(toml_value "$BUDGETS" "code_limits" "target_max_lines_per_file")"
HARD_LIMIT="$(toml_value "$BUDGETS" "code_limits" "hard_max_lines_per_file")"

if [ -z "$SOFT_LIMIT" ] || [ -z "$HARD_LIMIT" ]; then
  printf 'ERROR: the section [code_limits] of %s does not carry both limits.\n' "$BUDGETS" >&2
  exit 2
fi

say "==> Checking the length of the hand-written sources..."
say "    soft limit : ${SOFT_LIMIT} lines (a warning)"
say "    hard limit : ${HARD_LIMIT} lines (an error)"

MEASURED=0
SKIPPED_GENERATED=0
SOFT_FINDINGS=0
HARD_FINDINGS=0
SOFT_LIST=()
HARD_LIST=()

# Whether the first lines of a file say that a tool wrote it.
is_generated() {
  head -n 5 "$1" 2>/dev/null \
    | grep -qiE 'autogenerated|auto-generated|generated by|DO NOT EDIT|@generated'
}

# The number of lines of the implementation of a file: the lines before its
# test module. A file without a test module is measured in full.
#
# The test module is found by its declaration (`mod tests` at the left
# margin) and by the `#[cfg(test)]` attribute that stands in front of it.
# An attribute on a single item does not shorten the measurement: only a
# module does.
implementation_lines() {
  local file="$1"
  local total
  total="$(wc -l < "$file" | tr -d ' ')"
  local cut
  cut="$(awk '
    /^mod[[:space:]]+tests[[:space:]]*[{;]/ {
      # The declaration of the test module. The attribute that guards it
      # is in one of the three lines in front of it.
      for (i = NR - 3; i < NR; i++) {
        if (i > 0 && attribute[i] ~ /#\[cfg\(test\)\]/) { print NR - 1; exit }
      }
    }
    { attribute[NR] = $0 }
  ' "$file")"
  if [ -n "$cut" ] && [ "$cut" -lt "$total" ]; then
    printf '%s' "$cut"
  else
    printf '%s' "$total"
  fi
}

while IFS= read -r file; do
  [ -n "$file" ] || continue
  if is_generated "$file"; then
    SKIPPED_GENERATED=$((SKIPPED_GENERATED + 1))
    continue
  fi
  total="$(wc -l < "$file" | tr -d ' ')"
  lines="$(implementation_lines "$file")"
  MEASURED=$((MEASURED + 1))
  if [ "$lines" -gt "$HARD_LIMIT" ]; then
    HARD_FINDINGS=$((HARD_FINDINGS + 1))
    HARD_LIST+=("${lines} implementation, ${total} in total: ${file}")
  elif [ "$lines" -gt "$SOFT_LIMIT" ]; then
    SOFT_FINDINGS=$((SOFT_FINDINGS + 1))
    SOFT_LIST+=("${lines} implementation, ${total} in total: ${file}")
  fi
done < <(
  find . \
    \( -name target -o -name .git -o -name archive -o -name node_modules -o -name vendor -o -name build \) \
    -prune -o \
    \( -name '*.rs' -o -name '*.sh' -o -name '*.js' -o -name '*.mjs' -o -name '*.css' \
       -o -name '*.html' -o -name '*.kt' -o -name '*.swift' -o -name '*.py' \) \
    -type f -print | sort
)

if [ "${#SOFT_LIST[@]}" -gt 0 ]; then
  printf '\n--- %s file(s) above the soft limit of %s lines ---\n' \
    "${#SOFT_LIST[@]}" "$SOFT_LIMIT" >&2
  for entry in "${SOFT_LIST[@]}"; do
    printf '    %s\n' "$entry" >&2
  done
  printf '    The soft limit is a target, not an error: the gate stays green.\n' >&2
fi

if [ "${#HARD_LIST[@]}" -gt 0 ]; then
  printf '\n!!! %s file(s) above the hard limit of %s lines:\n' \
    "${#HARD_FINDINGS}" "$HARD_LIMIT" >&2
  for entry in "${HARD_LIST[@]}"; do
    printf '    %s\n' "$entry" >&2
  done
  printf '    A file above the hard limit is a finding: it has to be split.\n' >&2
fi

say ""
say "Files measured          : ${MEASURED}"
say "Generated files skipped : ${SKIPPED_GENERATED}"
say "Above the soft limit    : ${SOFT_FINDINGS}"
say "Above the hard limit    : ${HARD_FINDINGS}"

if [ "$SOFT_ONLY" -eq 1 ]; then
  say ""
  say "OK: the hard limit was not applied (--soft-only)."
  exit 0
fi

if [ "$HARD_FINDINGS" -gt 0 ]; then
  say ""
  say "FAILED: a hand-written source file is above the hard limit."
  exit 1
fi

say ""
say "OK: every hand-written source file is inside the hard limit of ${HARD_LIMIT} lines."
exit 0
